// ===== ぴったり入店ゲート：ゲームの調整値 =====
// 数字を書き換えて保存し、ゲームのページを再読み込みすると反映されます。
// 項目を消した場合や書き間違えた場合は、その項目だけゲーム内蔵の標準値が使われます。
// 「連続成功ごと」の値は、連続成功が1回増えるたびに足される量です。
// 速さの単位は「1秒あたりのピクセル数」で、ゲーム画面は横800×縦660です。
window.GAME_CONFIG = {

  // --- 店から指定される人数 ---
  target: {
    min: 5,                  // 指定人数の最小
    max: 18,                 // 指定人数の最大（連続成功ボーナスを足す前）
    bonusPerStreak: 1,       // 連続成功ごとに指定人数へ足す人数
    bonusMax: 6,             // 上の「足す人数」の上限
  },

  // --- ゲートを開けたときの人の勢い ---
  speed: {
    start: 45,               // 開けた瞬間の速さ
    startPerStreak: 4,       // 連続成功ごとに「開けた瞬間の速さ」に足す量
    accel: 32,               // 開けている間、1秒ごとに増える速さ
    accelPerStreak: 7,       // 連続成功ごとに「1秒ごとに増える速さ」に足す量
    personMin: 0.75,         // 1人ずつの速さの倍率（最小）。人によって速い・遅いの差が出る
    personMax: 1.35,         // 1人ずつの速さの倍率（最大）
    response: 6,             // 目標の速さに追いつく素早さ（大きいほどキビキビ動く）
  },

  // --- 行列の並び方 ---
  queue: {
    gap: 15,                 // 人と人の最小の間隔
    extraGap: 30,            // 間隔に足されるランダム分の最大値（大きいほど人がまばらに来る）
    firstDistance: 14,       // 先頭の人の、行列ゲートからの距離
    sideJitter: 6,           // 列からの左右のはみ出し具合
  },

  // --- 行列の出口ゲート（ボタンで開け閉めする） ---
  // ゲートを通った人数が「入店人数」として数えられます。
  gate: {
    stopDistance: 14,        // 閉まっているとき、人が止まる位置（ゲートからの距離）
    animSpeed: 18,           // ゲートバーと店の自動ドアが開閉する速さ（大きいほど速い）
    judgeDelayMs: 900,       // 通った人が全員店に入ってから、結果が出るまでの時間（ミリ秒）
  },

  // --- 店（自動ドアは、人が近づくと勝手に開きます） ---
  store: {
    approachSpeed: 120,      // ゲートを閉めた後、通路の人が店へ歩く速さ
    doorSensor: 70,          // 人が店のドアにこの距離まで近づくと自動ドアが開く
    walkSpeed: 220,          // 入店した人が席へ歩く速さ
  },

  // --- 表示する文章 ---
  // {target}=指定人数 {entered}=入った人数 {n}=過不足の人数 に置き換わります。
  texts: {
    requestTop: '{target}人',
    requestBottom: 'ちょうだい！',
    okTitle: 'ぴったり！ 大成功',
    okDetail: '{target}人ちょうど入店。次はもっと勢いが強くなります。',
    okBubble: ['ぴったり！', 'ありがとう！'],
    underTitle: '{n}人足りない…',
    underDetail: '入店 {entered}人 ／ 指定 {target}人。慎重すぎて席が空いてしまいました。',
    underBubble: ['あと{n}人', '足りないよ…'],
    overTitle: '{n}人オーバー！',
    overDetail: '入店 {entered}人 ／ 指定 {target}人。店内がパンクしました。',
    overBubble: ['{n}人多い！', '入りきらない！'],
  },
};
